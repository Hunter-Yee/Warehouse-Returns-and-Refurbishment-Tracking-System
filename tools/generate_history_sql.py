#!/usr/bin/env python3
"""Generate temporal history tables and capture triggers from a built schema.

Each core table <T> gets <T>History, which mirrors <T>'s columns and keeps every
version of a row with its validity period, the operation that produced it, who
made the change, and the transaction it belonged to.

Writes:
  database/01_schema/020_history_tables.sql
  database/02_programmability/050_history_triggers.sql

Usage (against any schema built from 01_schema/010_tables.sql):
  MYSQL_PWD=... python3 tools/generate_history_sql.py --host 127.0.0.1 --port 3306 \
      --user root --schema wr_build

Re-run after any column change to a core table, then commit both generated files.
Requires only the mysql command-line client (no Python packages).
"""
import argparse
import os
import subprocess
import sys

# Every base table except the AuditLog event log. Order = creation order.
CORE_TABLES = [
    "AppUser", "Role", "ReferenceValue", "Vendor", "Location", "Product",
    "ReturnHeader", "UserRole", "ReturnItem", "SalesSummary", "WorkOrder",
    "Inspection", "InventoryMovement", "VendorClaim",
]
OPEN_END = "'9999-12-31 23:59:59.999999'"
HISTORY_COLUMNS = [
    "ValidFrom", "ValidTo", "Operation", "ChangedByLogin", "ChangedByUserID", "TransactionID",
]


def query(args, sql):
    cmd = ["mysql", "--protocol=TCP", f"--host={args.host}", f"--port={args.port}",
           f"--user={args.user}", "--batch", "--skip-column-names", "--raw", "-e", sql]
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    return [line.split("\t") for line in out.splitlines() if line]


def load_tables(args):
    rows = query(args, f"""
        SELECT c.TABLE_NAME, c.COLUMN_NAME, c.COLUMN_TYPE, c.IS_NULLABLE, c.EXTRA
        FROM information_schema.COLUMNS c
        WHERE c.TABLE_SCHEMA = '{args.schema}'
        ORDER BY c.TABLE_NAME, c.ORDINAL_POSITION""")
    pk_rows = query(args, f"""
        SELECT k.TABLE_NAME, k.COLUMN_NAME
        FROM information_schema.KEY_COLUMN_USAGE k
        WHERE k.TABLE_SCHEMA = '{args.schema}' AND k.CONSTRAINT_NAME = 'PRIMARY'
        ORDER BY k.TABLE_NAME, k.ORDINAL_POSITION""")
    by_lower = {t.lower(): t for t in CORE_TABLES}  # macOS returns lowercase names
    tables = {t: {"cols": [], "pk": []} for t in CORE_TABLES}
    for tname, col, ctype, nullable, extra in rows:
        t = by_lower.get(tname.lower())
        if t is None or "GENERATED" in extra.upper():
            continue
        tables[t]["cols"].append((col, ctype, nullable == "YES"))
    for tname, col in pk_rows:
        t = by_lower.get(tname.lower())
        if t is not None:
            tables[t]["pk"].append(col)
    for t, meta in tables.items():
        if not meta["cols"] or not meta["pk"]:
            sys.exit(f"Table {t} not found in schema {args.schema} (or has no primary key)")
        clash = {c for c, _, _ in meta["cols"]} & set(HISTORY_COLUMNS + ["HistoryID"])
        if clash:
            sys.exit(f"{t} has columns that clash with history columns: {clash}")
    return tables


def snake(t):
    return t.lower()


def gen_tables(tables):
    out = [
        "-- GENERATED by tools/generate_history_sql.py. Do not edit by hand; re-run the generator.",
        "-- Temporal history (audit) tables: one per core table. Each row is one VERSION of a",
        "-- base-table row, valid from ValidFrom (inclusive) to ValidTo (exclusive).",
        f"-- The current version has ValidTo = {OPEN_END}. Operation: I=insert, U=update,",
        "-- D=delete (a D row records the deleted values; ValidFrom = ValidTo = delete time).",
        "-- Written only by the capture triggers in 050_history_triggers.sql; guard triggers make",
        "-- these tables append-only. No application role is granted direct access.",
        "",
    ]
    for t, meta in tables.items():
        h = f"{t}History"
        s = snake(t)
        lines = ["  HistoryID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY"]
        for col, ctype, nullable in meta["cols"]:
            lines.append(f"  {col} {ctype.upper()} {'NULL' if nullable else 'NOT NULL'}")
        lines += [
            "  ValidFrom DATETIME(6) NOT NULL",
            f"  ValidTo DATETIME(6) NOT NULL DEFAULT {OPEN_END}",
            "  Operation CHAR(1) NOT NULL",
            "  ChangedByLogin VARCHAR(100) NOT NULL",
            "  ChangedByUserID INT UNSIGNED NULL",
            "  TransactionID VARCHAR(64) NOT NULL",
            f"  CONSTRAINT ck_{s}h_operation CHECK (Operation IN ('I','U','D'))",
            f"  CONSTRAINT ck_{s}h_period CHECK (ValidTo >= ValidFrom)",
            f"  INDEX ix_{s}h_key ({', '.join(meta['pk'])}, ValidTo)",
            # Watermark index for intraday incremental warehouse loads.
            f"  INDEX ix_{s}h_valid_from (ValidFrom)",
            f"  INDEX ix_{s}h_transaction (TransactionID)",
        ]
        colnames = [c for c, _, _ in meta["cols"]]
        if {"ReturnID", "LineNumber"} <= set(colnames) and meta["pk"][:2] != ["ReturnID", "LineNumber"]:
            lines.append(f"  INDEX ix_{s}h_item (ReturnID, LineNumber, ValidFrom)")
        out.append(f"CREATE TABLE {h} (\n" + ",\n".join(lines) + "\n) ENGINE=InnoDB;\n")
    out.append("SELECT COUNT(*) AS history_table_count FROM information_schema.TABLES")
    out.append("WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE = 'BASE TABLE' AND TABLE_NAME LIKE '%History';")
    return "\n".join(out) + "\n"


def gen_triggers(tables):
    out = [
        "-- GENERATED by tools/generate_history_sql.py. Do not edit by hand; re-run the generator.",
        "-- Capture triggers: every INSERT/UPDATE/DELETE on a core table writes a version to its",
        "-- history table inside the same transaction (a rollback removes both).",
        "-- Who/when/transaction come from fn_audit_login(), fn_audit_user_id() and",
        "-- fn_audit_transaction_id() in 020_functions.sql. An UPDATE that changes no column",
        "-- writes nothing. Guard triggers make history tables append-only: the only update",
        "-- allowed is closing the open version (setting ValidTo once).",
        "DELIMITER $$",
        "",
    ]
    for t, meta in tables.items():
        h = f"{t}History"
        s = snake(t)
        cols = [c for c, _, _ in meta["cols"]]
        col_list = ", ".join(cols)
        pk_old = " AND ".join(f"{c} = OLD.{c}" for c in meta["pk"])
        hist_cols = f"{col_list}, ValidFrom, ValidTo, Operation, ChangedByLogin, ChangedByUserID, TransactionID"
        who = "fn_audit_login(), fn_audit_user_id(), fn_audit_transaction_id()"
        new_vals = ", ".join(f"NEW.{c}" for c in cols)
        old_vals = ", ".join(f"OLD.{c}" for c in cols)
        unchanged = "\n   AND ".join(f"OLD.{c} <=> NEW.{c}" for c in cols)
        close = (f"  UPDATE {h} SET ValidTo = v_now\n"
                 f"  WHERE {pk_old} AND ValidTo = {OPEN_END};\n")
        out.append(f"""-- {t} -> {h}
DROP TRIGGER IF EXISTS trg_{s}_hist_ai$$
CREATE TRIGGER trg_{s}_hist_ai AFTER INSERT ON {t}
FOR EACH ROW
BEGIN
 INSERT INTO {h} ({hist_cols})
 VALUES ({new_vals}, UTC_TIMESTAMP(6), {OPEN_END}, 'I', {who});
END$$
DROP TRIGGER IF EXISTS trg_{s}_hist_au$$
CREATE TRIGGER trg_{s}_hist_au AFTER UPDATE ON {t}
FOR EACH ROW
BEGIN
 DECLARE v_now DATETIME(6) DEFAULT UTC_TIMESTAMP(6);
 IF NOT ({unchanged}) THEN
{close}  INSERT INTO {h} ({hist_cols})
  VALUES ({new_vals}, v_now, {OPEN_END}, 'U', {who});
 END IF;
END$$
DROP TRIGGER IF EXISTS trg_{s}_hist_ad$$
CREATE TRIGGER trg_{s}_hist_ad AFTER DELETE ON {t}
FOR EACH ROW
BEGIN
 DECLARE v_now DATETIME(6) DEFAULT UTC_TIMESTAMP(6);
{close} INSERT INTO {h} ({hist_cols})
 VALUES ({old_vals}, v_now, v_now, 'D', {who});
END$$
""")
        frozen = "\n    AND ".join(f"OLD.{c} <=> NEW.{c}" for c in
                                    ["HistoryID"] + cols + [c for c in HISTORY_COLUMNS if c != "ValidTo"])
        out.append(f"""DROP TRIGGER IF EXISTS trg_{s}h_guard_bu$$
CREATE TRIGGER trg_{s}h_guard_bu BEFORE UPDATE ON {h}
FOR EACH ROW
BEGIN
 IF NOT (OLD.ValidTo = {OPEN_END} AND NEW.ValidTo <> {OPEN_END}
    AND {frozen}) THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '{h} is append-only: only closing the open version is allowed';
 END IF;
END$$
DROP TRIGGER IF EXISTS trg_{s}h_guard_bd$$
CREATE TRIGGER trg_{s}h_guard_bd BEFORE DELETE ON {h}
FOR EACH ROW
BEGIN
 SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '{h} is append-only: deletions are not permitted';
END$$
""")
    out.append("DELIMITER ;")
    out.append("")
    out.append("SELECT COUNT(*) AS history_trigger_count FROM information_schema.TRIGGERS")
    out.append("WHERE TRIGGER_SCHEMA = DATABASE() AND (TRIGGER_NAME LIKE 'trg\\_%\\_hist\\_%' OR TRIGGER_NAME LIKE 'trg\\_%h\\_guard\\_%');")
    return "\n".join(out) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", default="3306")
    p.add_argument("--user", default="root")
    p.add_argument("--schema", required=True, help="schema built from 01_schema/010_tables.sql")
    args = p.parse_args()
    if not args.schema.replace("_", "").isalnum():
        sys.exit("Invalid schema name")
    tables = load_tables(args)
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "database")
    targets = {
        os.path.join(root, "01_schema", "020_history_tables.sql"): gen_tables(tables),
        os.path.join(root, "02_programmability", "050_history_triggers.sql"): gen_triggers(tables),
    }
    for path, text in targets.items():
        with open(path, "w", newline="\n") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(path)}")


if __name__ == "__main__":
    main()
